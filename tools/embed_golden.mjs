// Regenerates web/src/golden-data.js from web/test/golden.json and the catalog so the
// in-browser self-test needs no fetch. Run after UPDATE_GOLDEN=1: node tools/embed_golden.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const golden = JSON.parse(readFileSync('web/test/golden.json', 'utf8'));
const catalog = JSON.parse(readFileSync('web/data/village_catalog.json', 'utf8'));
const out = '// Generated by tools/embed_golden.mjs. Do not edit by hand.\n' +
  `export const golden = ${JSON.stringify(golden)};\nexport const catalogEntries = ${JSON.stringify(catalog.entries)};\n`;
writeFileSync('web/src/golden-data.js', out);
console.log('wrote web/src/golden-data.js');
