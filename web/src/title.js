// Title screen decisions. Pure, no DOM, no randomness: the subtitle is the campaign's own first-night rumor.

const trim = (s) => String(s ?? '').replace(/^[#?]/, '');
const param = (search, hash, name) => new URLSearchParams(trim(hash)).get(name) ?? new URLSearchParams(trim(search)).get(name);

/**
 * Whether the title screen should show. Disabled by ?intro=0 or #intro=0. Deep links land directly on the scene:
 * #story=, #seed=, #sanity=, #night= (so shared links and tools/screenshot.sh callers are unaffected), and so do
 * ?view=3d, ?cinematic=1 and ?capture=1 which ask for a specific view or a clean take.
 */
export function shouldShowTitle(search, hash) {
  if (param(search, hash, 'intro') === '0') return false;
  for (const k of ['story', 'seed', 'sanity', 'night']) if (param(search, hash, k) !== null) return false;
  return param(search, hash, 'view') !== '3d' && param(search, hash, 'cinematic') !== '1' && param(search, hash, 'capture') !== '1';
}

/** ?webgl=0 pretends WebGL is missing, so the 2D fallback of the title screen can be checked on any machine. */
export const webglForcedOff = (search, hash) => param(search, hash, 'webgl') === '0';

/** A device that should not be asked to render a fly-through: few cores, little memory, or the data saver is on. */
export function lowPowerDevice(nav) {
  if (!nav) return false;
  const conn = nav.connection || {};
  return conn.saveData === true || (Number.isFinite(nav.hardwareConcurrency) && nav.hardwareConcurrency <= 2) || (Number.isFinite(nav.deviceMemory) && nav.deviceMemory <= 2);
}

/**
 * What the title screen offers. can3d: WebGL exists. recommend: the button that starts focused and answers Enter.
 * reasonKey: i18n key explaining a disabled or de-emphasised choice. backdrop: '3d' fly-through (a still frame under reduced motion), or '2d' drifting map.
 */
export function titleModel({ webgl, lowPower, reduced }) {
  const can3d = !!webgl;
  const recommend = can3d && !lowPower ? '3d' : '2d';
  const reasonKey = !can3d ? 'title.reason.nogl' : lowPower ? 'title.reason.lowpower' : '';
  // reduced motion keeps the 3D backdrop but frozen: the fly-through holds its first viewpoint and nothing animates
  const backdrop = can3d && !lowPower ? '3d' : '2d';
  return { can3d, recommend, reasonKey, backdrop, still: !!reduced };
}

/** Subtitle: the village name and the first night's rumor, both generated by the Core. Empty when there is no campaign. */
export function titleSubtitle(campaign) {
  const first = campaign && Array.isArray(campaign.nights) && campaign.nights[0];
  return { name: campaign && campaign.villageName ? campaign.villageName : '', rumor: first && first.rumor ? first.rumor : '' };
}

/** Beats for the title backdrop fly-through: many long beats, about three minutes before it holds on the last stop. */
export const BACKDROP_BEATS = Object.freeze(Array.from({ length: 24 }, () => 8000));
